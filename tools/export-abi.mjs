#!/usr/bin/env node
// Writes SaldaClearing's ABI from Foundry's build output into the web app as a typed constant, so viem infers
// every argument and return type. Run after `forge build`:
//   node tools/export-abi.mjs [contracts/out] [web/src/chain/abi.ts]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const outDir = process.argv[2] ?? "contracts/out";
const target = process.argv[3] ?? "web/src/chain/abi.ts";

const { abi } = JSON.parse(readFileSync(join(outDir, "SaldaClearing.sol", "SaldaClearing.json"), "utf8"));
if (!Array.isArray(abi) || abi.length === 0) {
  console.error(`No ABI found in ${outDir}. Run \`forge build\` first.`);
  process.exit(1);
}

const header = "// Generated by tools/export-abi.mjs from contracts/src/SaldaClearing.sol. Do not edit by hand.\n\n";
writeFileSync(target, `${header}export const saldaAbi = ${JSON.stringify(abi, null, 2)} as const;\n`);
console.log(`✓ ${abi.length} ABI entries written to ${target}`);
